import { useEffect, useState, type FormEvent } from 'react'
import { ApiError } from './api/session'
import {
  createSyntheticExchangeLink,
  createSyntheticSharingGrant,
  facilities,
  managementError,
  reviewSyntheticExchangeLink,
  revokeSyntheticSharingGrant,
  syntheticExchangeLinks,
  type Facility,
  type SyntheticExchangeLink,
  type SyntheticSharingGrant,
} from './api/management'
import type { Page } from './api/management'

export function SyntheticSharingDemo({ organizationId }: { organizationId: string }) {
  const [facilityList, setFacilityList] = useState<Facility[]>([])
  const [links, setLinks] = useState<SyntheticExchangeLink[]>([])
  const [facilityId, setFacilityId] = useState('')
  const [loading, setLoading] = useState(true)
  const [busy, setBusy] = useState(false)
  const [error, setError] = useState('')
  const [notice, setNotice] = useState('')

  async function load() {
    setError('')
    const [facilityPage, linkPage] = await Promise.all([
      facilities(organizationId, 1, 100),
      syntheticExchangeLinks(organizationId),
    ])
    setFacilityList(facilityPage.data)
    setLinks(linkPage.data)
    setFacilityId((current) => current || facilityPage.data[0]?.id || '')
  }

  useEffect(() => {
    let active = true
    Promise.all([facilities(organizationId, 1, 100), syntheticExchangeLinks(organizationId)])
      .then(([facilityPage, linkPage]: [Page<Facility>, Page<SyntheticExchangeLink>]) => {
        if (!active) return
        setFacilityList(facilityPage.data)
        setLinks(linkPage.data)
        setFacilityId((current) => current || facilityPage.data[0]?.id || '')
      })
      .catch((cause: unknown) => { if (active) setError(managementError(cause)) })
      .finally(() => { if (active) setLoading(false) })
    return () => { active = false }
  }, [organizationId])

  async function submitLink(event: FormEvent<HTMLFormElement>) {
    event.preventDefault()
    setBusy(true); setError(''); setNotice('')
    try {
      await createSyntheticExchangeLink(organizationId, facilityId)
      await load()
      setNotice('Synthetic references added to the manual review queue.')
    } catch (cause) {
      setError(cause instanceof ApiError && cause.status === 422
        ? 'The request was rejected. Choose a facility in this organization and submit only the synthetic demonstration fields.'
        : managementError(cause))
    } finally { setBusy(false) }
  }

  async function reviewLink(link: SyntheticExchangeLink, decision: 'confirmed' | 'rejected') {
    const action = decision === 'confirmed' ? 'Confirm these references for a synthetic walkthrough only?' : 'Reject this synthetic reference pair?'
    if (!window.confirm(action)) return
    setBusy(true); setError(''); setNotice('')
    try {
      await reviewSyntheticExchangeLink(organizationId, link.id, decision)
      await load()
      setNotice(decision === 'confirmed' ? 'References confirmed for this synthetic walkthrough only.' : 'Synthetic reference pair rejected.')
    } catch (cause) { setError(managementError(cause)) } finally { setBusy(false) }
  }

  async function issueGrant(link: SyntheticExchangeLink) {
    if (!window.confirm('Create a synthetic demonstration grant? It expires automatically after 24 hours and does not authorize or send clinical data.')) return
    setBusy(true); setError(''); setNotice('')
    try {
      await createSyntheticSharingGrant(organizationId, link.id)
      await load()
      setNotice('Synthetic demonstration grant created. No clinical data was shared.')
    } catch (cause) { setError(managementError(cause)) } finally { setBusy(false) }
  }

  async function revokeGrant(grant: SyntheticSharingGrant) {
    if (!window.confirm('Revoke this synthetic demonstration grant?')) return
    setBusy(true); setError(''); setNotice('')
    try {
      await revokeSyntheticSharingGrant(organizationId, grant.id)
      await load()
      setNotice('Synthetic demonstration grant revoked.')
    } catch (cause) { setError(managementError(cause)) } finally { setBusy(false) }
  }

  return <div className="dashboard-data">
    <div className="dashboard-roadmap" role="note">
      <strong>Synthetic workflow demonstration only.</strong>
      <p>Use random references only. This feature stores no names, demographics, clinical records, consent evidence, or partner data, and it does not connect to MedPass or transmit data. A confirmed reference pair is not a verified patient identity or legal authorization.</p>
    </div>
    {error && <p className="auth-error" role="alert">{error}</p>}
    {notice && <p role="status">{notice}</p>}
    <section className="dashboard-panel">
      <h2>Create a synthetic reference pair</h2>
      <p>New pairs use random references generated by the server, start pending, and contain no patient information. A permitted reviewer must confirm or reject them.</p>
      {facilityList.length === 0 && !loading ? <p>Add a facility before creating a demonstration pair.</p> : (
        <form className="management-form" onSubmit={(event) => { void submitLink(event) }}>
          <label htmlFor="synthetic-facility">Facility</label>
          <select id="synthetic-facility" required value={facilityId} onChange={(event) => setFacilityId(event.target.value)}>
            {facilityList.map((facility) => <option key={facility.id} value={facility.id}>{facility.name}</option>)}
          </select>
          <button className="button button-primary" disabled={busy || !facilityId} type="submit">{busy ? 'Saving...' : 'Generate references and add to review queue'}</button>
        </form>
      )}
    </section>
    <section className="dashboard-panel">
      <h2>Reference review and demonstration grants</h2>
      {loading ? <p>Loading synthetic workflow records...</p> : links.length === 0 ? <p>No synthetic reference pairs have been added.</p> : (
        <div className="report-table-container">
          <table className="report-table">
            <caption>Fictional UUID references only; no clinical exchange occurs.</caption>
            <thead><tr><th>Facility</th><th>Synthetic local reference</th><th>Synthetic recipient reference</th><th>Review state</th><th>Actions / demo grants</th></tr></thead>
            <tbody>{links.map((link) => {
              const facilityName = facilityList.find((facility) => facility.id === link.facility_id)?.name ?? 'Facility'
              return <tr key={link.id}>
                <td>{facilityName}</td>
                <td><code>{link.local_subject_reference}</code></td>
                <td><code>{link.recipient_subject_reference}</code></td>
                <td>{link.review_status === 'confirmed' ? 'Confirmed for synthetic walkthrough only' : link.review_status}</td>
                <td>
                  {link.review_status === 'pending' && <div className="management-actions">
                    <button className="dashboard-action" disabled={busy} type="button" onClick={() => { void reviewLink(link, 'confirmed') }}>Confirm synthetic pair</button>
                    <button className="dashboard-action" disabled={busy} type="button" onClick={() => { void reviewLink(link, 'rejected') }}>Reject</button>
                  </div>}
                  {link.review_status === 'confirmed' && !link.grants.some((grant) => grant.status === 'active') && (
                    <button className="dashboard-action" disabled={busy} type="button" onClick={() => { void issueGrant(link) }}>Create 24-hour demo grant</button>
                  )}
                  {link.grants.map((grant) => <p key={grant.id}>
                    Demo grant: {grant.status}; expires {new Date(grant.expires_at).toLocaleString()}
                    {grant.status === 'active' && <button className="dashboard-action" disabled={busy} type="button" onClick={() => { void revokeGrant(grant) }}>Revoke</button>}
                  </p>)}
                </td>
              </tr>
            })}</tbody>
          </table>
        </div>
      )}
    </section>
  </div>
}
